import chroma from "chroma-js";

export function RALtoChroma(entry: any) {
    if (entry.lab) return chroma.lab(entry.lab[0], entry.lab[1], entry.lab[2]);
    if (entry.hlc) return chroma.hcl(entry.hlc[0], entry.hlc[2], entry.hlc[1]);
    throw new Error("Unsupported & Unexpected RAL Entry");
}

export default function RALMatch(
    input: [number, number, number],
    subset: "classic" | "design" | null = null
) {
    const colorInput = chroma.oklch(input[0], input[1], input[2]);
    let closest = null;
    let dist = Infinity;
    if (subset == "classic" || subset == null) {
        for (let colorTestEntry of RAL_CLASSIC) {
            const colorTest = RALtoChroma(colorTestEntry);
            let distTest = chroma.deltaE(colorInput, colorTest);
            if (distTest < dist) {
                dist = distTest;
                closest = colorTestEntry;
            }
        }
    }
    if (subset == "design" || subset == null) {
        for (let colorTestEntry of RAL_DESIGN) {
            const colorTest = RALtoChroma(colorTestEntry);
            let distTest = chroma.deltaE(colorInput, colorTest);
            if (distTest < dist) {
                dist = distTest;
                closest = colorTestEntry;
            }
        }
    }
    if (closest == null) throw new Error("No Match Found");
    return closest;
}
